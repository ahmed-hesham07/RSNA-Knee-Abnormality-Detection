    "        \n",
    "        # Try primary match from CSV\n",
    "        if len(study_matches) > 0:\n",
    "            for _, row in study_matches.iterrows():\n",
    "                s_id = str(row['SeriesInstanceUID'])\n",
    "                direct_path = os.path.join(CFG.test_series_dir, str(study_id), s_id)\n",
