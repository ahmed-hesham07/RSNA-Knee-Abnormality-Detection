    "def extract_geometry(dcm):\n",
    "    try:\n",
    "        pos = np.array([float(i) for i in dcm.ImagePositionPatient])\n",
    "        ori = np.array([float(i) for i in dcm.ImageOrientationPatient])\n",
    "        spacing = np.array([float(i) for i in dcm.PixelSpacing])\n",
    "        normal = np.cross(ori[0:3], ori[3:6])\n",
    "        z_pos = np.dot(pos, normal)\n",
    "        return z_pos, spacing\n",
    "    except:\n",
    "        return None, None\n",
    "\n",
    "def sort_dicom_files(file_paths):\n",
    "    valid_files = []\n",
    "    for f in file_paths:\n",
    "        try:\n",
    "            dcm = pydicom.dcmread(f, stop_before_pixels=True)\n",
    "            z_pos, _ = extract_geometry(dcm)\n",
    "            if z_pos is not None:\n",
    "                valid_files.append((z_pos, getattr(dcm, 'InstanceNumber', 0), f))\n",
    "            else:\n",
    "                valid_files.append((0.0, getattr(dcm, 'InstanceNumber', 0), f))\n",
    "        except:\n",
    "            continue\n",
    "    valid_files.sort(key=lambda x: (x[0], x[1], x[2]))\n",
    "    return [f[2] for f in valid_files]\n",
    "\n",
    "def read_and_crop_dicom(filepath, crop_mm, target_size):\n",
    "    try:\n",
    "        dcm = pydicom.dcmread(filepath)\n",
    "        img = apply_voi_lut(dcm.pixel_array, dcm)\n",
    "        if dcm.PhotometricInterpretation == 'MONOCHROME1':\n",
    "            img = np.amax(img) - img\n",
    "        img = img - np.min(img)\n",
    "        img = img / (np.max(img) + 1e-6)\n",
    "        img = (img * 255).astype(np.uint8)\n",
    "        \n",
    "        spacing_y, spacing_x = 1.0, 1.0\n",
    "        if hasattr(dcm, 'PixelSpacing'):\n",
    "            try:\n",
    "                spacing_y, spacing_x = [float(s) for s in dcm.PixelSpacing]\n",
    "            except:\n",
    "                pass\n",
    "        \n",
    "        h, w = img.shape\n",
    "        crop_h = min(int(crop_mm / spacing_y), h)\n",
    "        crop_w = min(int(crop_mm / spacing_x), w)\n",
    "        start_y = (h - crop_h) // 2\n",
    "        start_x = (w - crop_w) // 2\n",
    "        \n",
    "        cropped_img = img[start_y:start_y+crop_h, start_x:start_x+crop_w]\n",
    "        return cv2.resize(cropped_img, (target_size, target_size), interpolation=cv2.INTER_CUBIC)\n",
    "    except:\n",
    "        return np.zeros((target_size, target_size), dtype=np.uint8)\n"
