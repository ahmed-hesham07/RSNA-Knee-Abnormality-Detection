    "        series_dir = self._find_series_dir(study_id)\n",
    "        \n",
    "        sorted_files = []\n",
    "        if series_dir and os.path.exists(series_dir):\n",
    "            dcm_files = [os.path.join(series_dir, f) for f in os.listdir(series_dir) if f.endswith('.dcm')]\n",
    "            if dcm_files:\n",
