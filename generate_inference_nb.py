    "def extract_physical_geometry(dcm):\n",
    "    try:\n",
    "        pos = np.array([float(i) for i in dcm.ImagePositionPatient])\n",
    "        ori = np.array([float(i) for i in dcm.ImageOrientationPatient])\n",
    "        spacing = np.array([float(i) for i in dcm.PixelSpacing])\n",
    "    except:\n",
    "        return None, None, None, None\n",
    "    \n",
    "    row_cosines = ori[0:3]\n",
    "    col_cosines = ori[3:6]\n",
    "    normal = np.cross(row_cosines, col_cosines)\n",
    "    slice_position = np.dot(pos, normal)\n",
    "    return pos, spacing, normal, slice_position\n",
    "\n",
    "def load_dicom_volume(study_dir):\n",
    "    slices = []\n",
    "    for f in os.listdir(study_dir):\n",
    "        if f.endswith('.dcm'):\n",
    "            filepath = os.path.join(study_dir, f)\n",
    "            try:\n",
    "                dcm = pydicom.dcmread(filepath, stop_before_pixels=True)\n",
    "                _, spacing, _, z_pos = extract_physical_geometry(dcm)\n",
    "                if z_pos is not None:\n",
    "                    slices.append({\n",
    "                        'filepath': filepath,\n",
    "                        'z': z_pos,\n",
    "                        'spacing': spacing\n",
    "                    })\n",
    "            except:\n",
    "                continue\n",
    "                \n",
    "    if not slices:\n",
    "        return None\n",
    "        \n",
    "    # Sort anatomically by physical Z position\n",
    "    slices.sort(key=lambda x: x['z'])\n",
    "    \n",
    "    # Pick center 3 slices\n",
    "    n = len(slices)\n",
    "    if n >= 3:\n",
    "        mid = n // 2\n",
    "        chosen = [slices[mid-1], slices[mid], slices[mid+1]]\n",
    "    elif n == 2:\n",
    "        chosen = [slices[0], slices[0], slices[1]]\n",
    "    else:\n",
    "        chosen = [slices[0], slices[0], slices[0]]\n",
    "        \n",
    "    # Read pixels\n",
    "    volume = []\n",
    "    for s in chosen:\n",
    "        dcm = pydicom.dcmread(s['filepath'])\n",
    "        img = dcm.pixel_array\n",
    "        img = apply_voi_lut(img, dcm)\n",
    "        if dcm.PhotometricInterpretation == \"MONOCHROME1\":\n",
    "            img = np.max(img) - img\n",
    "        img = img - np.min(img)\n",
    "        img = img / (np.max(img) + 1e-6)\n",
    "        img = (img * 255).astype(np.uint8)\n",
    "        \n",
    "        # Center Crop using physical mm\n",
    "        h, w = img.shape\n",
    "        py, px = s['spacing']\n",
    "        crop_h = int(CFG.crop_size_mm / py)\n",
    "        crop_w = int(CFG.crop_size_mm / px)\n",
    "        \n",
    "        cy, cx = h//2, w//2\n",
    "        y1 = max(0, cy - crop_h//2)\n",
    "        y2 = min(h, cy + crop_h//2)\n",
    "        x1 = max(0, cx - crop_w//2)\n",
    "        x2 = min(w, cx + crop_w//2)\n",
    "        \n",
    "        img_cropped = img[y1:y2, x1:x2]\n",
    "        img_resized = cv2.resize(img_cropped, (CFG.img_size, CFG.img_size))\n",
    "        volume.append(img_resized)\n",
    "        \n",
    "    return np.stack(volume, axis=-1) # Shape: (H, W, 3)"
