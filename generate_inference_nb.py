    "def run_inference():\n",
    "    num_classes = len(CFG.target_cols)\n",
    "    \n",
    "    # 1. Load Data\n",
    "    if os.path.exists(CFG.sample_sub_csv):\n",
    "        sample_sub = pd.read_csv(CFG.sample_sub_csv)\n",
    "        print(f\"Loaded sample_submission.csv: {sample_sub.shape}\")\n",
    "    else:\n",
    "        sample_sub = pd.DataFrame({\n",
    "            'StudyInstanceUID': ['dummy_1', 'dummy_2']\n",
    "        })\n",
    "        for col in CFG.target_cols:\n",
    "            sample_sub[col] = 0.5\n",
    "            \n",
    "    if os.path.exists(CFG.test_csv):\n",
    "        test_df = pd.read_csv(CFG.test_csv)\n",
    "    else:\n",
    "        test_df = sample_sub[['StudyInstanceUID']].copy()\n",
    "        \n",
    "    if os.path.exists(CFG.test_series_csv):\n",
    "        test_series_df = pd.read_csv(CFG.test_series_csv)\n",
    "    else:\n",
    "        test_series_df = pd.DataFrame(columns=['StudyInstanceUID', 'SeriesInstanceUID'])\n",
    "        \n",
    "    dataset = RSNAKneeInferenceDataset(test_df, test_series_df)\n",
    "    dataloader = DataLoader(\n",
    "        dataset, \n",
    "        batch_size=CFG.batch_size, \n",
    "        shuffle=False, \n",
    "        num_workers=CFG.num_workers,\n",
    "        pin_memory=True\n",
    "    )\n",
    "    \n",
    "    # 2. Load 5-Fold Models\n",
    "    models = []\n",
    "    model_paths = sorted(glob.glob(os.path.join(CFG.weights_dir, \"*.pth\")))\n",
    "    print(f\"Found {len(model_paths)} model weights:\")\n",
    "    for pth in model_paths:\n",
    "        print(f\"  --> Loading {os.path.basename(pth)}\")\n",
    "        model = DINOv2KneeModel(num_classes=num_classes)\n",
    "        model.load_state_dict(torch.load(pth, map_location=device))\n",
    "        model.to(device)\n",
    "        model.eval()\n",
    "        models.append(model)\n",
    "        \n",
    "    if not models:\n",
    "        print(\"⚠️ No .pth weights found! Initializing single model fallback.\")\n",
    "        model = DINOv2KneeModel(num_classes=num_classes).to(device)\n",
    "        model.eval()\n",
    "        models.append(model)\n",
    "        \n",
    "    # 3. Predict\n",
    "    all_study_ids = []\n",
    "    all_preds = []\n",
    "    \n",
    "    with torch.no_grad():\n",
    "        for images, study_ids in tqdm(dataloader, desc=\"Inference\"):\n",
    "            images = images.to(device)\n",
    "            batch_preds = torch.zeros((images.shape[0], num_classes), device=device)\n",
    "            \n",
    "            for model in models:\n",
    "                batch_preds += torch.sigmoid(model(images))\n",
    "            batch_preds /= len(models)\n",
    "            \n",
    "            all_study_ids.extend(study_ids)\n",
    "            all_preds.append(batch_preds.cpu().numpy())\n",
    "            \n",
    "    all_preds = np.vstack(all_preds)\n",
    "    pred_df = pd.DataFrame(all_preds, columns=CFG.target_cols)\n",
    "    pred_df['StudyInstanceUID'] = all_study_ids\n",
    "    \n",
    "    # 4. Strictly Align with sample_submission.csv format\n",
    "    submission_df = sample_sub[['StudyInstanceUID']].merge(pred_df, on='StudyInstanceUID', how='left')\n",
    "    submission_df = submission_df.fillna(0.5)\n",
    "    \n",
    "    # Enforce exact column order from sample_sub\n",
    "    final_cols = ['StudyInstanceUID'] + [c for c in CFG.target_cols if c in sample_sub.columns or c != 'StudyInstanceUID']\n",
    "    submission_df = submission_df[final_cols]\n",
    "    \n",
    "    submission_df.to_csv('submission.csv', index=False)\n",
    "    print(f\"\\nSubmission generated successfully: {submission_df.shape}\")\n",
    "    return submission_df\n",
    "\n",
    "if __name__ == '__main__':\n",
    "    sub = run_inference()\n",
    "    display(sub.head(10))\n"
