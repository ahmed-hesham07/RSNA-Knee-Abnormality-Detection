    "def run_inference():\n",
    "    # 1. Read Test Data\n",
    "    try:\n",
    "        test_df = pd.read_csv(CFG.test_csv)\n",
    "        sample_sub = pd.read_csv(f'{CFG.base_dir}/sample_submission.csv')\n",
    "        target_cols = [c for c in sample_sub.columns if c != 'row_id']\n",
    "        num_classes = len(target_cols)\n",
    "    except Exception as e:\n",
    "        print(f\"Could not load test data. Running on dummy data for save... {e}\")\n",
    "        # Dummy fallback so notebook saves cleanly\n",
    "        test_df = pd.DataFrame({'study_id': ['12345'], 'row_id': ['12345']})\n",
    "        target_cols = [f'target_{i}' for i in range(12)]\n",
    "        num_classes = 12\n",
    "\n",
    "    dataset = RSNATestDataset(test_df)\n",
    "    dataloader = DataLoader(dataset, batch_size=CFG.batch_size, shuffle=False, num_workers=CFG.num_workers)\n",
    "    \n",
    "    # 2. Load Models\n",
    "    models = []\n",
    "    model_paths = glob.glob(f\"{CFG.weights_dir}/*.pth\")\n",
    "    if not model_paths:\n",
    "        print(\"⚠️ Warning: No .pth models found in weights directory! Will output dummy predictions.\")\n",
    "    \n",
    "    for pth in model_paths:\n",
    "        print(f\"Loading model: {pth}\")\n",
    "        model = RSNAKneeModel(CFG.model_name, num_classes=num_classes)\n",
    "        model.load_state_dict(torch.load(pth, map_location=device))\n",
    "        model.to(device)\n",
    "        model.eval()\n",
    "        models.append(model)\n",
    "        \n",
    "    # 3. Predict\n",
    "    all_row_ids = []\n",
    "    all_preds = []\n",
    "    \n",
    "    with torch.no_grad():\n",
    "        for images, row_ids in dataloader:\n",
    "            images = images.to(device)\n",
    "            \n",
    "            # Ensemble averaging\n",
    "            batch_preds = torch.zeros((images.shape[0], num_classes)).to(device)\n",
    "            if models:\n",
    "                for model in models:\n",
    "                    logits = model(images)\n",
    "                    batch_preds += torch.sigmoid(logits)\n",
    "                batch_preds /= len(models)\n",
    "            \n",
    "            all_row_ids.extend(row_ids)\n",
    "            all_preds.append(batch_preds.cpu().numpy())\n",
    "            \n",
    "    if all_preds:\n",
    "        all_preds = np.vstack(all_preds)\n",
    "    else:\n",
    "        all_preds = np.zeros((len(test_df), num_classes))\n",
    "        \n",
    "    # 4. Save Submission\n",
    "    sub_df = pd.DataFrame(all_preds, columns=target_cols)\n",
    "    sub_df['row_id'] = all_row_ids\n",
    "    \n",
    "    # Reorder columns to match sample_submission\n",
    "    cols = ['row_id'] + target_cols\n",
    "    sub_df = sub_df[cols]\n",
    "    \n",
    "    sub_df.to_csv('submission.csv', index=False)\n",
    "    print(\"Saved submission.csv!\")\n",
    "    return sub_df\n",
    "\n",
    "if __name__ == '__main__':\n",
    "    submission = run_inference()\n",
    "    display(submission.head())"
